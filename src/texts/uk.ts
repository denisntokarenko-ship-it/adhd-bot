export function clarifyReason(kind: "unclear" | "event_no_date" | "past" | "bad_format" | "too_far"): string {
  switch (kind) {
    case "past":
      return "цей час уже позаду, коли саме?";
    case "too_far":
      return "це дуже далеко, коли саме?";
    case "event_no_date":
      return "коли?";
    default:
      return "коли саме?";
  }
}

